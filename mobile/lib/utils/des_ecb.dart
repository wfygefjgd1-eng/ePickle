  DesEcbPkcs7._();

  static String decryptBase64Utf8(String encoded, String keyText) {
    final key = utf8.encode(keyText);
    if (key.length < 8) throw const FormatException('DES key is too short');
    final clear = decrypt(
      Uint8List.fromList(base64.decode(encoded)),
      Uint8List.fromList(key.take(8).toList()),
    );
    return utf8.decode(clear);
  }

  static Uint8List decrypt(Uint8List encrypted, Uint8List key) {
    if (key.length != 8) throw const FormatException('DES requires 8-byte key');
    if (encrypted.isEmpty || encrypted.length % 8 != 0) {
      throw const FormatException('Invalid DES block length');
    }

    final subKeys = _subKeys(_read64(key, 0));
    final padded = Uint8List(encrypted.length);
    for (var offset = 0; offset < encrypted.length; offset += 8) {
      final block = _cryptBlock(_read64(encrypted, offset), subKeys);
      _write64(padded, offset, block);
    }

    final padding = padded.last;
    if (padding < 1 || padding > 8 || padding > padded.length) {
      throw const FormatException('Invalid DES padding');
    }
    for (var i = padded.length - padding; i < padded.length; i++) {
      if (padded[i] != padding) {
        throw const FormatException('Invalid DES padding');
      }
    }
    return Uint8List.sublistView(padded, 0, padded.length - padding);
  }

  static int _cryptBlock(int block, List<int> subKeys) {
    final initial = _permute(block, 64, _initialPermutation);
    var left = (initial >> 32) & 0xffffffff;
    var right = initial & 0xffffffff;
    for (var round = 15; round >= 0; round--) {
      final next = left ^ _feistel(right, subKeys[round]);
      left = right;
      right = next & 0xffffffff;
    }
    return _permute((right << 32) | left, 64, _finalPermutation);
  }

  static int _feistel(int value, int subKey) {
    final expanded = _permute(value, 32, _expansion) ^ subKey;
    var substituted = 0;
    for (var box = 0; box < 8; box++) {
      final six = (expanded >> (42 - box * 6)) & 0x3f;
      final row = ((six & 0x20) >> 4) | (six & 1);
      final column = (six >> 1) & 0x0f;
      substituted = (substituted << 4) | _sBoxes[box][row * 16 + column];
    }
    return _permute(substituted, 32, _pPermutation);
  }

  static List<int> _subKeys(int key) {
    final selected = _permute(key, 64, _permutedChoice1);
    var left = (selected >> 28) & 0x0fffffff;
    var right = selected & 0x0fffffff;
    final result = <int>[];
    for (final shift in _keyShifts) {
      left = ((left << shift) | (left >> (28 - shift))) & 0x0fffffff;
      right = ((right << shift) | (right >> (28 - shift))) & 0x0fffffff;
      result.add(_permute((left << 28) | right, 56, _permutedChoice2));
    }
    return result;
  }

  static int _permute(int value, int inputBits, List<int> table) {
    var result = 0;
    for (final position in table) {
      result = (result << 1) | ((value >> (inputBits - position)) & 1);
    }
    return result;
  }

  static int _read64(Uint8List bytes, int offset) {
    var value = 0;
    for (var i = 0; i < 8; i++) {
      value = (value << 8) | bytes[offset + i];
    }
    return value;
  }

  static void _write64(Uint8List bytes, int offset, int value) {
    for (var i = 7; i >= 0; i--) {
      bytes[offset + i] = value & 0xff;
      value >>= 8;
    }
  }

